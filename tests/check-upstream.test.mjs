test("dirty upstream working tree: --sync is refused and copies nothing; --force proceeds", () => {
  const w = world();
  put(w.upstream, "examples/agent-hook-plugin/scripts/hook.mjs", "// committed v2\n");
  commit(w.upstream, "v2");
  put(w.upstream, "examples/agent-hook-plugin/scripts/hook.mjs", "// UNCOMMITTED v3\n");

  const refused = tool(w, "--sync", "--json");
  assert.equal(refused.status, 1);
  assert.equal(refused.report.sync.refused, true);
  assert.ok(refused.report.errors.some((e) => e.includes("sync refused")));
  assert.equal(readFileSync(join(w.project, "scripts", "hook.mjs"), "utf8"), HOOK_V1, "project file untouched");
  assert.equal(refused.report.upstream.dirty, true);

  const forced = tool(w, "--sync", "--force", "--json");
  assert.equal(forced.status, 0, forced.stdout + forced.stderr);
  assert.equal(readFileSync(join(w.project, "scripts", "hook.mjs"), "utf8"), "// UNCOMMITTED v3\n");
});

test("the tool never modifies the upstream clone (tree hash incl. .git is unchanged)", () => {
  const w = world();
  put(w.upstream, "examples/agent-hook-plugin/scripts/hook.mjs", "// v2\n");
  commit(w.upstream, "v2");
  put(w.upstream, "examples/agent-hook-plugin/hosts/zcode.mjs", "// uncommitted change\n"); // dirty on purpose
  const before = treeHash(w.upstream);

  tool(w);
  tool(w, "--json");
  tool(w, "--strict");
  tool(w, "--sync", "--json");
  tool(w, "--sync", "--force");
  tool(w, "--update-lock");

  assert.equal(treeHash(w.upstream), before);
});

test("missing lock exits 1; missing --upstream and a non-git path exit 2", () => {
  const w = world();
  const noLock = makeTmp("upcheck-nolock");
  const missing = spawnSync(process.execPath, [TOOL, "--upstream", w.upstream, "--installed", w.installed, "--project", noLock], { encoding: "utf8" });
  assert.equal(missing.status, 1);
  assert.match(missing.stdout, /upstream\.lock\.json not found/);

  const noArg = spawnSync(process.execPath, [TOOL, "--project", w.project], { encoding: "utf8", env: { ...process.env, OPENVIKING_UPSTREAM: "" } });
  assert.equal(noArg.status, 2);
  assert.match(noArg.stderr, /usage:/);

  const notGit = spawnSync(process.execPath, [TOOL, "--upstream", noLock, "--project", w.project], { encoding: "utf8" });
  assert.equal(notGit.status, 2);

  const bad = spawnSync(process.execPath, [TOOL, "--bogus"], { encoding: "utf8" });
  assert.equal(bad.status, 2);

  const viaEnv = spawnSync(process.execPath, [TOOL, "--installed", w.installed, "--project", w.project], {
    encoding: "utf8",
    env: { ...process.env, OPENVIKING_UPSTREAM: w.upstream },
  });
  assert.equal(viaEnv.status, 0, viaEnv.stdout + viaEnv.stderr);
});

